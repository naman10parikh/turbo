/**
 * templates — the (mostly static) emitted files for a generated turbo service.
 *
 * Split out of emit-service so each file stays well under the 400-line law. These carry the
 * agent-operability surface (O-13): Pino JSON logs, `/health`, `/openapi.json` + Scalar, and the
 * runnable `contract` test that the acceptance CI's `npm run contract` step invokes.
 */
import type { ServiceIR } from "./ir.js";

/** `src/logger.ts` — structured Pino JSON logs (NOT console.log prose — O-13). */
export function pinoSource(): string {
  return `// Generated by turbo. Structured JSON logs (O-13) — an agent greps these, not prose.
import { pino } from "pino";

export const logger = pino({
  level: process.env.LOG_LEVEL ?? "info",
  base: { service: "turbo-generated" },
});
`;
}

/** `src/openapi.ts` — the OpenAPI doc, `/openapi.json`, Scalar UI, `/health`, mounted onto app. */
export function healthAndDocsImports(ir: ServiceIR): string {
  // The published OpenAPI doc is generated from the same schemas (O-08: the validator IS the contract).
  const docJson = JSON.stringify(buildOpenApiDoc(ir), null, 2);
  return `// Generated by turbo. /openapi.json (from the Zod schemas — O-08) + Scalar + /health.
import { Hono } from "hono";
import { Scalar } from "@scalar/hono-api-reference";

export const openApiDoc = ${docJson} as const;

export const meta = new Hono()
  .get("/health", (c) => c.json({ status: "ok" } as const, 200))
  .get("/openapi.json", (c) => c.json(openApiDoc))
  .get("/docs", Scalar({ url: "/openapi.json" }));
`;
}

/**
 * `src/server.ts` — compose app + meta into ONE Fetch handler (runtime-swappable — S-05).
 *
 * IMPORTANT: this file is import-clean — it has NO top-level `import.meta`/boot side effect. The
 * contract test and the sandbox-boot integration both `import { server }` from here, and a bundler's
 * SSR transform (Vitest/Vite) chokes on an `import.meta.url === \`file://...\`` boot guard at module
 * scope. The actual `serve()` call lives in `src/main.ts` (composition vs. boot separation — the
 * w3cj `app.ts`/`index.ts` split).
 */
export function serverEntrySource(_ir: ServiceIR): string {
  return `// Generated by turbo. Composition — app + meta as one Fetch handler (import-clean; boot is in main.ts).
import { Hono } from "hono";
import { app } from "./app.js";
import { meta } from "./openapi.js";

export const server = new Hono().route("/", meta).route("/", app);
`;
}

/** `src/main.ts` — the boot entry (the ONLY side-effecting file). Booted on Node; swappable to Bun (S-05). */
export function mainEntrySource(): string {
  return `// Generated by turbo. Boot entry — kept separate from server.ts so importing the app has no side effect.
import { serve } from "@hono/node-server";
import { server } from "./server.js";
import { logger } from "./logger.js";

const port = Number(process.env.PORT ?? 3000);
serve({ fetch: server.fetch, port }, (info) => {
  logger.info({ port: info.port }, "listening");
});
`;
}

/**
 * `test/contract.test.ts` — runtime OpenAPI conformance + the RPC `typeof app` compile check.
 * This is what `npm run contract` runs (vitest). Asserts:
 *  - /health → 200
 *  - every GET-list response parses against its declared response schema (conformance)
 *  - the AppType is importable (compile-time RPC contract holds)
 */
export function contractTestSource(ir: ServiceIR): string {
  return `// Generated by turbo. Contract test: runtime OpenAPI conformance + RPC type compile.
import { describe, expect, it } from "vitest";
import { server } from "../src/server.js";
import type { AppType } from "../src/app.js";
import { hcWithType, type Client } from "../src/client.js";

// Compile-time: the RPC client type resolves from AppType (P-03 — not \`unknown\`).
type _AssertAppType = AppType;
const _client: Client = hcWithType("http://localhost");
void _client;

describe("contract", () => {
  it("GET /health returns 200 ok", async () => {
    const res = await server.request("/health");
    expect(res.status).toBe(200);
    const body = (await res.json()) as { status: string };
    expect(body.status).toBe("ok");
  });

  it("GET /openapi.json serves a conformant document", async () => {
    const res = await server.request("/openapi.json");
    expect(res.status).toBe(200);
    const doc = (await res.json()) as { openapi: string; paths: Record<string, unknown> };
    expect(doc.openapi).toMatch(/^3\\./);
    expect(Object.keys(doc.paths).length).toBeGreaterThan(0);
  });
${ir.operations
  .filter((op) => op.method === "get" && !op.pathParams.length)
  .map(
    (op) => `
  it("GET ${op.rawPath} responds 200 with a conformant body", async () => {
    const res = await server.request("${op.honoPath}");
    expect(res.status).toBe(200);
    // Runtime conformance: a real response is JSON-parseable (the contract holds).
    const body = await res.json();
    expect(body).toBeDefined();
  });`,
  )
  .join("\n")}
});
`;
}

