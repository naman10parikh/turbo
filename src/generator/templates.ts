// --- internal: build the OpenAPI doc that the service publishes (from the IR) -----------------

interface OAProp {
  type?: string;
  enum?: readonly string[];
  items?: OAProp;
  properties?: Record<string, OAProp>;
  minLength?: number;
}

function irNodeToOA(schema: {
  kind: string;
  enumValues?: readonly string[];
  items?: unknown;
  properties?: ReadonlyArray<{ name: string; schema: unknown }>;
  minLength?: number;
}): OAProp {
  switch (schema.kind) {
    case "enum":
      return { type: "string", enum: schema.enumValues };
    case "array":
      return { type: "array", items: irNodeToOA(schema.items as never) };
    case "object": {
      const properties: Record<string, OAProp> = {};
      for (const p of schema.properties ?? []) properties[p.name] = irNodeToOA(p.schema as never);
      return { type: "object", properties };
    }
    case "integer":
      return { type: "integer" };
    case "number":
      return { type: "number" };
    case "boolean":
      return { type: "boolean" };
    case "string":
      return schema.minLength !== undefined
        ? { type: "string", minLength: schema.minLength }
        : { type: "string" };
    default:
      return {};
  }
}

function buildOpenApiDoc(ir: ServiceIR): Record<string, unknown> {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const op of ir.operations) {
    const pathKey = op.rawPath;
    paths[pathKey] = paths[pathKey] ?? {};
    const entry: Record<string, unknown> = {
      operationId: op.operationId,
      summary: op.summary,
      responses: {
        [String(op.responseStatus)]: {
          description: "ok",
          content: op.responseSchema
            ? { "application/json": { schema: irNodeToOA(op.responseSchema as never) } }
            : undefined,
        },
      },
    };
    if (op.pathParams.length > 0) {
      entry.parameters = op.pathParams.map((p) => ({
        name: p.name,
        in: "path",
        required: true,
        schema: { type: "string" },
      }));
    }
    if (op.requestSchema) {
      entry.requestBody = {
        required: true,
        content: { "application/json": { schema: irNodeToOA(op.requestSchema as never) } },
      };
    }
    paths[pathKey][op.method] = entry;
  }
  return {
    openapi: "3.1.0",
    info: { title: ir.title, version: ir.version },
    paths,
  };
}
