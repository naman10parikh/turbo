/**
 * emit-service — assemble the generated Hono service files from the ServiceIR.
 *
 * Produces a law-compliant typed service: Zod schemas at every boundary, routes chained into ONE
 * `AppType` (so `hcWithType` infers — P-03 guard), `/openapi.json` + Scalar, `/health`, Pino JSON
 * logs (O-13), a `hcWithType` client, and a runnable `contract` test. Every emitted file stays
 * < 400 lines (the law) by splitting schemas / app / client / test into separate files.
 *
 * Returns a map of relativePath -> fileContents; the writer (write-tree) is responsible for I/O.
 */
import { emitNamedSchema, emitSchema } from "./emit-zod.js";
import type { IROperation, ServiceIR } from "./ir.js";
import {
  contractTestSource,
  gitignoreSource,
  healthAndDocsImports,
  mainEntrySource,
  packageJsonSource,
  pinoSource,
  serverEntrySource,
  tsconfigSource,
} from "./templates.js";

function pascal(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

/** The exported Zod symbol name for a named component schema. */
function schemaExportName(name: string): string {
  return `${pascal(name)}Schema`;
}

/** Emit `src/schemas.ts` — all named component schemas as Zod exports. */
function emitSchemasFile(ir: ServiceIR): string {
  const header = `// Generated by turbo. Zod schemas at every boundary (the law).\nimport { z } from "zod";\n`;
  const body = ir.namedSchemas
    .map((ns) => {
      // A component whose name reads as a partial-update shape gets the no-default PATCH treatment.
      const partial = /update|patch/i.test(ns.name);
      return emitNamedSchema(schemaExportName(ns.name), ns.schema, { partial });
    })
    .join("\n\n");
  return `${header}\n${body}\n`;
}

/** Resolve the request/response Zod expression for an operation (inline or a named ref). */
function schemaExprFor(
  _ir: ServiceIR,
  op: IROperation,
  which: "request" | "response",
): string | undefined {
  const schema = which === "request" ? op.requestSchema : op.responseSchema;
  if (!schema) return undefined;
  if (schema.refName) {
    const partial = which === "request" && op.isPartialUpdate;
    // For a PATCH whose body refs a named schema, still emit a dedicated no-default inline (P-04).
    if (partial) return `${emitSchema(schema, true)}.partial()`;
    // Qualify with the `S` namespace alias that app.ts imports (`import * as S from "./schemas.js"`).
    return `S.${schemaExportName(schema.refName)}`;
  }
  const dropDefaults = which === "request" && op.isPartialUpdate;
  return emitSchema(schema, dropDefaults);
}

/** Emit one route handler block for `src/app.ts`. */
function emitRoute(ir: ServiceIR, op: IROperation): string {
  const reqExpr = schemaExprFor(ir, op, "request");
  const respExpr = schemaExprFor(ir, op, "response") ?? "z.unknown()";
  const lines: string[] = [];
  lines.push(`  // ${op.summary} (${op.method.toUpperCase()} ${op.rawPath})`);

  // Build the route inline; chain everything onto `app` so the AppType captures it (P-03).
  const honoMethod = op.method;
  const validators: string[] = [];
  if (op.pathParams.length > 0) {
    const paramObj = op.pathParams.map((p) => `${JSON.stringify(p.name)}: z.string()`).join(", ");
    validators.push(`zValidator("param", z.object({ ${paramObj} }))`);
  }
  if (reqExpr && (op.method === "post" || op.method === "patch" || op.method === "put")) {
    validators.push(`zValidator("json", ${reqExpr})`);
  }
  const validatorArgs = validators.length > 0 ? `, ${validators.join(", ")}` : "";

  // The handler echoes a contract-conformant body parsed through the response schema.
  lines.push(`  .${honoMethod}(${JSON.stringify(op.honoPath)}${validatorArgs}, (c) => {`);
  lines.push(`    const responseSchema = ${respExpr};`);
  if (respExpr.startsWith("z.array(")) {
    lines.push(`    const body = responseSchema.parse([]);`);
  } else {
    lines.push(`    const sample = buildSample(responseSchema);`);
    lines.push(`    const body = responseSchema.parse(sample);`);
  }
  lines.push(`    return c.json(body, ${op.responseStatus} as 200);`);
  lines.push(`  })`);
  return lines.join("\n");
}

/** Emit `src/app.ts` — the chained Hono app + exported AppType. */
function emitAppFile(ir: ServiceIR): string {
  const routeBlocks = ir.operations.map((op) => emitRoute(ir, op)).join("\n");
  return `// Generated by turbo. Routes chained into ONE AppType (hcWithType infers — P-03).
import { Hono } from "hono";
import { zValidator } from "@hono/zod-validator";
import { z } from "zod";
import * as S from "./schemas.js";
import { buildSample } from "./sample.js";
import { logger } from "./logger.js";

// Re-export named schemas under a stable namespace for handlers + tests.
export const schemas = S;

export const app = new Hono()
  .use("*", async (c, next) => {
    const start = Date.now();
    await next();
    logger.info({ method: c.req.method, path: c.req.path, ms: Date.now() - start }, "request");
  })
${routeBlocks};

export type AppType = typeof app;
`;
}

/** Emit `src/client.ts` — the precompiled hcWithType client (never raw hc — P-03). */
function emitClientFile(): string {
  return `// Generated by turbo. hcWithType precompiled client (P-03: never raw hc).
import { hc } from "hono/client";
import type { AppType } from "./app.js";

// Precompute the client type once, then re-export a typed factory (the hcWithType pattern).
const _client = hc<AppType>("");
export type Client = typeof _client;
export const hcWithType = (...args: Parameters<typeof hc>): Client =>
  hc<AppType>(...args);
`;
}

/** Emit `src/sample.ts` — a tiny Zod-driven sample builder so handlers return conformant bodies. */
function emitSampleFile(): string {
  return `// Generated by turbo. Build a minimal value that satisfies a Zod schema (for stub handlers).
import { z } from "zod";

export function buildSample(schema: z.ZodTypeAny): unknown {
  const def = (schema as { _def?: { typeName?: string } })._def;
  const typeName = def?.typeName ?? "";
  if (schema instanceof z.ZodObject) {
    const shape = schema.shape as Record<string, z.ZodTypeAny>;
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(shape)) out[key] = buildSample(value);
    return out;
  }
  if (schema instanceof z.ZodArray) return [];
  if (schema instanceof z.ZodEnum) return (schema.options as string[])[0];
  if (schema instanceof z.ZodOptional || schema instanceof z.ZodDefault) {
    return buildSample((schema as unknown as { unwrap: () => z.ZodTypeAny }).unwrap());
  }
  if (typeName.includes("String") || schema instanceof z.ZodString) return "sample";
  if (typeName.includes("Number") || schema instanceof z.ZodNumber) return 0;
  if (typeName.includes("Boolean") || schema instanceof z.ZodBoolean) return false;
  return null;
}
`;
}

/**
 * Generate the full service file tree from the IR.
 * Caller passes the service name (the output dir basename) for package.json.
 */
export function emitService(ir: ServiceIR, serviceName: string): Map<string, string> {
  const files = new Map<string, string>();
  files.set("src/schemas.ts", emitSchemasFile(ir));
  files.set("src/app.ts", emitAppFile(ir));
  files.set("src/client.ts", emitClientFile());
  files.set("src/sample.ts", emitSampleFile());
  files.set("src/logger.ts", pinoSource());
  files.set("src/server.ts", serverEntrySource(ir));
  files.set("src/main.ts", mainEntrySource());
  files.set("src/openapi.ts", healthAndDocsImports(ir));
  files.set("test/contract.test.ts", contractTestSource(ir));
  files.set("package.json", packageJsonSource(serviceName));
  files.set("tsconfig.json", tsconfigSource());
  files.set(".gitignore", gitignoreSource());
  return files;
}
